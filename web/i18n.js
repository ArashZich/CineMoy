// t('Added to {name}', { name }). Numbers come out in Farsi digits in Farsi.
export function t(text, vars) {
  const template = lang === 'fa' ? FA[text] ?? text : text;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (all, k) => {
    if (!(k in vars)) return all;
    return lang === 'fa' && typeof vars[k] === 'number' ? faDigits(vars[k]) : String(vars[k]);
  });
}

// Static markup: <a data-t="Home">, <input data-t-placeholder="Search">, data-t-title, data-t-aria-label.
export function translateDom(root = document) {
  root.querySelectorAll('[data-t]').forEach(el => { el.textContent = t(el.dataset.t); });
  for (const attr of ['placeholder', 'title', 'aria-label']) {
    root.querySelectorAll(`[data-t-${attr}]`).forEach(el => el.setAttribute(attr, t(el.getAttribute(`data-t-${attr}`))));
  }
}
